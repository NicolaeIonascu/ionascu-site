// Converts public/_redirects (Netlify / Cloudflare format) into Apache and Nginx rules.
// Run after editing _redirects:   node tools/server-redirects.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const rules = readFileSync('public/_redirects', 'utf8').split(/\r?\n/)
  .map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split(/\s+/)).filter((p) => p.length >= 2)
  .map(([from, to, code]) => ({ from, to, code: code || '301' }));
const trim = (s) => s.replace(/\/$/, '');
mkdirSync('server', { recursive: true });
writeFileSync('server/redirects.htaccess',
  '# Generated by tools/server-redirects.mjs from public/_redirects. Paste into the site\'s .htaccess (before other rules).\n' +
  rules.map((r) => `RedirectMatch ${r.code} "^${trim(r.from)}/?$" ${r.to}`).join('\n') + '\n');
writeFileSync('server/redirects.nginx.conf',
  '# Generated by tools/server-redirects.mjs from public/_redirects. Include inside the server { } block.\n' +
  rules.map((r) => `location = ${r.from} { return ${r.code} ${r.to}; }`).join('\n') + '\n');
console.log(`${rules.length} redirects written to server/redirects.htaccess and server/redirects.nginx.conf`);